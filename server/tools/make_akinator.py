keys = [k for k, _ in QUESTIONS]
lines = [
    "// Generated by server/tools/make_akinator.py. Do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    f"#define AKI_QUESTIONS {len(QUESTIONS)}",
    f"#define AKI_ANIMALS {len(ANIMALS)}",
    "static const char *const AKI_QUESTION[AKI_QUESTIONS] = {",
]
lines += [f'    "{text}",' for _, text in QUESTIONS]
lines += ["};", "static const char *const AKI_NAME[AKI_ANIMALS] = {"]
lines += [f'    "{name}",' for name in ANIMALS]
lines += ["};", "// bit q is set when the answer to question q is yes", "static const uint32_t AKI_YES[AKI_ANIMALS] = {"]
for name, attrs in ANIMALS.items():
    mask = 0
    for a in attrs.split():
        mask |= 1 << keys.index(a)
    lines.append(f"    0x{mask:05X},  // {name}")
lines.append("};")
out = Path(__file__).resolve().parents[2] / "firmware" / "main" / "aki_data.h"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(ANIMALS)} animals, {len(QUESTIONS)} questions -> {out}")
